def _interp(table, x, clamp_high=True):
    keys = sorted(table)
    if x <= keys[0]:
        return table[keys[0]]
    if x >= keys[-1]:
        return table[keys[-1]]
    for a, b in zip(keys, keys[1:]):
        if a <= x <= b:
            return table[a] + (table[b] - table[a]) * (x - a) / (b - a)
    return table[keys[-1]]


def _ins(insulation):
    return "pvc" if str(insulation).lower() == "pvc" else "xlpe"


def base_table(material="copper", insulation="xlpe", method="C", loaded=3):
    """{mm2: A} for the reference conditions, or None if not tabulated."""
    ins = _ins(insulation)
    loaded = 3 if int(loaded or 3) >= 3 else 2
    method = (method or "C").upper()
    if method in ("E", "F"):
        t = TABLES_E_F.get((ins, material))
        if not t:
            return None
        col = {("E", 2): "E2", ("E", 3): "E3",
               ("F", 2): "F2", ("F", 3): "F3"}[(method, loaded)]
        return t[col]
    t = TABLES_A_TO_D.get((ins, loaded, material))
    return t.get(method) if t else None


def correction_factor(insulation="xlpe", method="C", ambient_c=30.0,
                      ground_c=20.0, soil_resistivity=2.5, n_grouped=1,
                      arrangement=None):
    """
    Product of the temperature, soil and grouping corrections, with the
    individual factors for the report.
    """
    ins = _ins(insulation)
    method = (method or "C").upper()
    n = max(1, int(n_grouped or 1))
    out = {}
    if method in GROUND_METHODS:
        out["temperature"] = _interp(AMBIENT_GROUND[ins], ground_c)
        out["soil"] = _interp(SOIL[method], soil_resistivity)
        out["grouping"] = _interp(
            GROUP_GROUND_DUCT if method == "D1" else GROUP_GROUND_DIRECT, n)
    else:
        out["temperature"] = _interp(AMBIENT_AIR[ins], ambient_c)
        out["soil"] = 1.0
        if method in ("E", "F"):
            grp = GROUP_TRAY
        elif method == "C" and arrangement != "bunched":
            grp = GROUP_SINGLE_LAYER
        else:
            grp = GROUP_BUNCHED
        out["grouping"] = _interp(grp, n)
    out["total"] = out["temperature"] * out["soil"] * out["grouping"]
    return out
